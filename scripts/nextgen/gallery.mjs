import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;'}[c]));
const safeLabel = label => /^[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(label);
const shotKey = shot => `${shot.scenario}\u0000${shot.room ?? ''}\u0000${shot.frame ?? ''}`;

/** Match actual scenario/room/frame identities; never pair unrelated screenshots. */
export function matchGalleryShots(left, right) {
  const first = new Map(left.map(shot => [shotKey(shot), shot]));
  const second = new Map(right.map(shot => [shotKey(shot), shot]));
  return [...new Set([...first.keys(), ...second.keys()])].map(key => ({left: first.get(key) ?? null, right: second.get(key) ?? null}));
}

/** Produce a portable comparison without launching a server or browser. */
export async function compareGalleries(base, labels, output) {
  assert(labels.length === 2 && labels.every(safeLabel), '--compare needs two safe gallery labels');
  const galleries = await Promise.all(labels.map(async label => {
    const directory = resolve(base, label);
    const manifest = JSON.parse(await readFile(resolve(directory, 'manifest.json'), 'utf8'));
    return {label, directory, manifest};
  }));
  const pairs = matchGalleryShots(galleries[0].manifest.shots, galleries[1].manifest.shots);
  async function card(shot, gallery) {
    if (!shot) return '<div class="missing">Not captured in this gallery</div>';
    // Manifest paths are local basenames generated by the runner, never arbitrary files.
    assert(/^[a-zA-Z0-9._-]+\.png$/.test(shot.file), 'Unsafe screenshot file in manifest');
    const data = (await readFile(resolve(gallery.directory, shot.file))).toString('base64');
    return `<figure><img src="data:image/png;base64,${data}" alt="${escape(gallery.label)} / ${escape(shot.file)}" loading="lazy"><figcaption>${escape(shot.file)} · simulation ${shot.simulationMs ?? 'unknown'} ms</figcaption></figure>`;
  }
  const sections = await Promise.all(pairs.map(async pair => {
    const shot = pair.left ?? pair.right;
    return `<section><h2>${escape(shot.scenario)}${shot.room ? ` / ${escape(shot.room)}` : ''}${shot.frame ? ` / frame ${shot.frame}` : ''}</h2><div class="pair">${await card(pair.left, galleries[0])}${await card(pair.right, galleries[1])}</div></section>`;
  }));
  const html = `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Containment / ${escape(labels.join(' vs '))}</title><style>body{margin:0;background:#081119;color:#e3f2f8;font:15px system-ui}header,section{padding:22px 28px}header{position:sticky;top:0;background:#081119f5;z-index:1;border-bottom:1px solid #39505c}h1{font-size:24px;margin:0 0 12px}h2{font-size:16px;margin:0 0 12px}.pair,.labels{display:grid;grid-template-columns:1fr 1fr;gap:18px}.labels span{color:#9fe8ff}p,figcaption{color:#afc3cf;font-size:12px;line-height:1.5}figure{margin:0;border:1px solid #39505c;background:#10202a}img{display:block;width:100%;height:auto}figcaption{padding:10px}.missing{display:grid;place-items:center;min-height:160px;border:1px dashed #53616b;color:#a4b1bb}</style><header><h1>CONTAINMENT / EXPERIENCE COMPARISON</h1><div class="labels">${galleries.map(g => `<span>${escape(g.label)} · ${g.manifest.viewport.width}×${g.manifest.viewport.height}<br><small>${escape(g.manifest.gitSHA)}</small></span>`).join('')}</div><p>Matched by scenario, room and frame. Missing views remain explicit. Different viewport sizes and simulation timestamps are recorded; this is a visual review, not pixel equivalence.</p></header><main>${sections.join('')}</main></html>`;
  await mkdir(output, {recursive: true});
  await Promise.all(['index.html', 'compare.html'].map(file => writeFile(resolve(output, file), html)));
  await writeFile(resolve(output, 'comparison.json'), JSON.stringify({labels, pairs: pairs.length, missingLeft: pairs.filter(p => !p.left).length, missingRight: pairs.filter(p => !p.right).length}, null, 2) + '\n');
  return {file: resolve(output, 'compare.html'), pairs: pairs.length};
}
